def test_question_keyword_routing():
    """Verify that general question words and '?' route to GENERAL intent in keyword detection."""
    executor = WorkflowExecutor(use_llm_intent=False)
    
    # Simple question word queries without calculation indicators
    intent, confidence = executor.detect_intent_with_confidence("why is the sky blue")
    assert intent == WorkflowIntent.GENERAL

    intent, confidence = executor.detect_intent_with_confidence("how do you do it?")
    assert intent == WorkflowIntent.GENERAL

    intent, confidence = executor.detect_intent_with_confidence("can we import this?")
    assert intent == WorkflowIntent.GENERAL


@pytest.mark.asyncio
async def test_general_client_payload_generate_answer():
    """Verify that GeneralServiceClient passes generate_answer=True and handles returned final_answer."""
    mock_client = AsyncMock()
    # Mocking the _post response of GeneralServiceClient
    client = GeneralServiceClient(base_url="http://localhost:8005")
    
    # Mock return value of post
    client._post = AsyncMock(return_value={
        "status": "success",
        "documents": [{"content": "Doc 1"}],
        "final_answer": "This is the final answer generated by microservice."
    })
    
    result = await client.ask(query="test question", generate_answer=True)
    
    # Assert that _post was called with generate_answer=True
    client._post.assert_called_once()
    payload = client._post.call_args[0][1]
    assert payload["generate_answer"] is True
    
    # Assert that the local LLM generation was skipped and final_answer preserved
    assert result["final_answer"] == "This is the final answer generated by microservice."


@pytest.mark.asyncio
async def test_formatter_bypass_for_general_with_final_answer():
    """Verify that OrchestratorFormatterService bypasses LLM formatting for general intent if has_final_answer is true."""
    config = FormatterServiceConfig(enabled=True)
    formatter = OrchestratorFormatterService(config)
    
    # Mock the providers to see if they are called
    mock_gemini = MagicMock()
    mock_gemini.is_available.return_value = True
    mock_gemini.format_response_stream = AsyncMock()
    formatter.providers["gemini"] = mock_gemini
    formatter._provider = mock_gemini
    
    # Case 1: has_final_answer is True -> should bypass Gemini provider and yield directly
    chunks = []
    async for chunk in formatter.format_response_stream(
        base_answer="Microservice answer",
        question="What is import procedure?",
        intent="general",
        context={"has_final_answer": True}
    ):
        chunks.append(chunk)
        
    assert "".join(chunks) == "Microservice answer"
    mock_gemini.format_response_stream.assert_not_called()
    
    # Case 2: has_final_answer is False -> should call Gemini provider normally
    chunks2 = []
    mock_gemini.format_response_stream.return_value = AsyncMock()
    async def mock_stream(*args, **kwargs):
        yield "Formatted answer"
    mock_gemini.format_response_stream = mock_stream
    
    async for chunk in formatter.format_response_stream(
        base_answer="Microservice answer",
        question="What is import procedure?",
        intent="general",
        context={"has_final_answer": False}
    ):
        chunks2.append(chunk)
        
    assert "".join(chunks2) == "Formatted answer"
